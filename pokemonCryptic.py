def solve(template, fodder, list):
    countFodder = Counter(fodder.upper())
    
    knownLetters = []
    wildcardIndices = []
    fitsTemplate = []
    
    for i,letter in enumerate(template.upper()):
        if letter != '*':
            knownLetters += [[i,letter]]
        if letter == '*':
            wildcardIndices.append(i)
    
    for item in list:
        if len(item) == len(template):
            if all(item[knownLetter[0]] == knownLetter[1] for knownLetter in knownLetters):
                if all(item[i] != ' ' for i in wildcardIndices):
                    fitsTemplate.append(item)
    
    matches = []
    for item in fitsTemplate:
        countItem = Counter(item)
        if all(countItem[letter] >= countFodder[letter] for letter in countFodder):
            matches.append(item)
    return matches

